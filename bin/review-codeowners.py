#!/usr/bin/env python3
"""review-codeowners.py OWNERS... [--policy .review-tiers]: print a CODEOWNERS file from the review policy, so GitHub
itself enforces human review where the plan allows it (org repos on Team/Enterprise with "Require review from Code
Owners" on, or a ruleset).

GitHub uses the LAST matching CODEOWNERS line, and a line with no owner means "no code owner review". So:
  * OWNERS                      everything needs a human (default deny)
  <agent glob>                  ownerless: agent-only paths
  <human glob> OWNERS           human paths repeated last, so they win over an agent glob that also matches
  .review-tiers / CODEOWNERS / .github/** OWNERS   the rules themselves are always human
OWNERS are GitHub handles or teams (@org/team). They must be HUMAN accounts the agents never use: a PR's author
can't approve their own PR, and every agent PR is opened from the owner's account.
"""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from review_tier import parse_policy  # noqa: E402

def main():
    a = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    a.add_argument("owners", nargs="+"); a.add_argument("--policy", default=".review-tiers")
    o = a.parse_args()
    bad = [w for w in o.owners if not w.startswith("@")]
    if bad: sys.exit(f"owners must be @handles or @org/teams: {bad}")
    rules, default, _ = parse_policy(open(o.policy).read())
    own = " ".join(o.owners)
    out = ["# Generated by review-codeowners.py from .review-tiers. Edit .review-tiers, not this file.",
           f"* {own}" if default == "human" else "# default agent: no catch-all owner"]
    out += [pat for t, _, pat in rules if t == "agent"]
    out += [f"{pat} {own}" for t, _, pat in rules if t == "human"]
    out += [f"/.review-tiers {own}", f"/.github/ {own}", f"/CODEOWNERS {own}", f"/.github/CODEOWNERS {own}"]
    print("\n".join(out))

if __name__ == "__main__":
    main()
